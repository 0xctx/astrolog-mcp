#!/usr/bin/env bash
# Maintainers only. Generates test/fixtures/parity-*.json and parity-transits-ny-1990.json from the Python
# reference implementation (the `astro` CLI). Run by hand once, or again when the pins change. `npm run test:parity` reads the
# committed fixtures and never runs this script, so it needs neither the reference toolkit nor astrolog.
# The midpoint lists come from `view --midpoints old --harmonic H`: the CLI has no `midpoints` subcommand.
# Needs: `astro` on PATH (or ASTRO=/path/to/astro), uv and the astrolog binary, plus node 22.
set -euo pipefail

ASTRO="${ASTRO:-astro}"
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
OUT="$ROOT/test/fixtures"
WORK="$(mktemp -d)"
trap 'rm -rf "$WORK"' EXIT

# Global pins, placed before the subcommand as the CLI requires: the contract's houses, zodiac and node,
# and the 12 objects the parity test uses (10 planets, Chiron, North Node; the oracle skips the South Node).
PINS=(--houses placidus --zodiac tropical --node mean
  --points "sun,moon,mercury,venus,mars,jupiter,saturn,uranus,neptune,pluto,chiron,north_node")
# The vibrational pack: classic midpoint orb 1.5 and its 17-aspect set. `view` otherwise uses the profile's pack.
PACK=(--pack vibrational)
MIDPOINT_HARMONICS=(1 2 3 5 8 16 29 32)
# The transit fixture: one date, in UT, for the ny-1990 chart only.
TRANSIT_DATE="2000-06-15"
TRANSIT_TIME="12:00"

# name|date|time|tz|at  (UT offsets; `at` is astrolog's lettered latitude and longitude)
CHARTS=(
  "ny-1990|1990-06-15|14:30|-05:00|40N42 73W54"
  "sydney-1985|1985-07-20|08:15|+10:00|33S52 151E12"
  "london-2000|2000-01-01|00:00|+00:00|51N30 0W10"
)

# Runs one oracle command, saves its JSON to the work dir and records the command line for the fixture.
run_oracle() {
  local out="$1"
  shift
  "$ASTRO" --json "${PINS[@]}" "$@" > "$WORK/$out"
  printf '%s --json %s %s\n' "$ASTRO" "${PINS[*]}" "$*" >> "$WORK/$name.commands"
}

# Trims one chart's oracle output to what the parity test reads, with the oracle's own numbers unchanged.
TRIM='
import { readFileSync } from "node:fs";
const env = process.env;
const read = (file) => JSON.parse(readFileSync(`${env.PARITY_WORK}/${file}`, "utf8"));
const names = { sun: "Sun", moon: "Moo", mercury: "Mer", venus: "Ven", mars: "Mar", jupiter: "Jup",
  saturn: "Sat", uranus: "Ura", neptune: "Nep", pluto: "Plu", chiron: "Chi", north_node: "Nor",
  asc: "ASC", mc: "MC", dsc: "DSC", ic: "IC" };
const code = (key) => {
  if (!(key in names)) throw new Error(`unexpected key ${key}`);
  return names[key];
};
const name = env.PARITY_NAME;
const natal = read(`${name}.view-1.json`);
const chart = natal.chart;
if (chart.profile.houses !== "Placidus" || chart.profile.zodiac !== "tropical" || chart.profile.node !== "mean") {
  throw new Error("the oracle did not run with the pinned settings");
}
if (chart.points.length !== 12 || chart.cusps.length !== 12) throw new Error("unexpected body or cusp count");
const bodies = {};
for (const p of chart.points) {
  bodies[code(p.key)] = { longitude: p.lon, speed: p.speed, retrograde: p.retrograde, house: p.house };
}
const houses = Object.fromEntries(chart.cusps.map((lon, i) => [i + 1, lon]));
const angles = Object.fromEntries(Object.entries(chart.angles).map(([key, lon]) => [code(key), lon]));
const positions = {
  bodies,
  houses,
  angles,
  missing: [],
  housesFrom: "placidus",
  provenance: {
    astrologVersion: chart.astrolog.version,
    source: "astrolog",
    utc: chart.moment.utc.replace("+00:00", "Z"),
  },
};
const midpoints = {};
for (const h of JSON.parse(env.PARITY_HARMONICS)) {
  const view = read(`${name}.view-${h}.json`);
  midpoints[h] = Object.entries(view.midpoints).flatMap(([focus, contacts]) =>
    contacts.map((c) => ({
      focus: code(focus),
      a: code(c.a),
      b: code(c.b),
      aspect: c.aspect,
      midpoint: c.midpoint,
      orb: c.orb,
      limit: c.limit,
      strength: c.strength,
    })),
  );
}
const harmonics = read(`${name}.harmonics.json`).harmonics.map((row) => ({
  harmonic: row.harmonic,
  old: row.old,
  oldStructures: row.old_structures.map((s) => ({
    focus: code(s.focus),
    a: code(s.a),
    b: code(s.b),
    aspect: s.aspect,
    strength: s.strength,
  })),
}));
const fixture = {
  description:
    "Golden output of the Python reference implementation for one fixed chart: natal positions, classic (old) " +
    "midpoint contacts per harmonic, and the old-method rows of the harmonics table, one per harmonic. Generated by " +
    "scripts/generate-parity-fixtures.sh; do not edit by hand.",
  chart: JSON.parse(env.PARITY_CHART),
  commands: readFileSync(`${env.PARITY_WORK}/${name}.commands`, "utf8").trim().split("\n"),
  positions,
  midpoints,
  harmonics,
};
process.stdout.write(JSON.stringify(fixture, null, 2) + "\n");
'

# Trims the oracle's `transits` output for one date to the sky's bodies, the transit aspects and the commands.
# The natal positions are not repeated here: the test reads them from parity-<name>.json, the same chart.
TRIM_TRANSITS='
import { readFileSync } from "node:fs";
const env = process.env;
const read = (file) => JSON.parse(readFileSync(`${env.PARITY_WORK}/${file}`, "utf8"));
const names = { sun: "Sun", moon: "Moo", mercury: "Mer", venus: "Ven", mars: "Mar", jupiter: "Jup",
  saturn: "Sat", uranus: "Ura", neptune: "Nep", pluto: "Plu", chiron: "Chi", north_node: "Nor",
  asc: "ASC", mc: "MC", dsc: "DSC", ic: "IC" };
const code = (key) => {
  if (!(key in names)) throw new Error(`unexpected key ${key}`);
  return names[key];
};
const name = env.PARITY_NAME;
const transits = read(`${name}.transits.json`);
const sky = transits.sky;
if (sky.points.length !== 12) throw new Error("unexpected sky body count");
const bodies = {};
for (const p of sky.points) {
  bodies[code(p.key)] = { longitude: p.lon, speed: p.speed, retrograde: p.retrograde };
}
const commands = readFileSync(`${env.PARITY_WORK}/${name}.commands`, "utf8").trim().split("\n");
const transitCommand = commands[commands.length - 1];
if (!transitCommand.includes(" transits ")) throw new Error("the last command is not the transits run");
const fixture = {
  description:
    "Golden output of the Python reference implementation for the transits of one UT date to the parity-ny-1990 " +
    "natal chart, with the vibrational pack: each transiting body, with its best aspect to each natal body, ASC and " +
    "MC, and the orb, limit, strength and applying flag the reference reports. Generated by " +
    "scripts/generate-parity-fixtures.sh; do not edit by hand.",
  chart: JSON.parse(env.PARITY_CHART),
  commands: [commands[0], transitCommand],
  provenance: {
    astrologVersion: sky.astrolog.version,
    source: "astrolog",
    utc: sky.moment.utc.replace("+00:00", "Z"),
  },
  sky: { bodies },
  transits: transits.transits.map((t) => ({
    transit: code(t.transit),
    natal: code(t.natal),
    aspect: t.aspect,
    angle: t.angle,
    orb: t.orb,
    limit: t.limit,
    strength: t.strength,
    applying: t.applying,
  })),
};
process.stdout.write(JSON.stringify(fixture, null, 2) + "\n");
'

mkdir -p "$OUT"
for spec in "${CHARTS[@]}"; do
  IFS='|' read -r name date time tz at <<<"$spec"
  chart=(--date "$date" --time "$time" --tz="$tz" "--at=$at")
  : > "$WORK/$name.commands"

  run_oracle "$name.view-1.json" view "${chart[@]}" "${PACK[@]}" --show positions --midpoints old --harmonic 1
  for h in "${MIDPOINT_HARMONICS[@]}"; do
    [ "$h" = 1 ] && continue
    run_oracle "$name.view-$h.json" view "${chart[@]}" "${PACK[@]}" --show positions --midpoints old --harmonic "$h"
  done
  # --top 32 lists all 32 harmonic rows. Each row keeps the oracle's top three old structures (its default).
  run_oracle "$name.harmonics.json" harmonics "${chart[@]}" "${PACK[@]}" --harmonics 1-32 --top 32

  chart_json=$(printf '{"date":"%s","time":"%s","tz":"%s","at":"%s"}' "$date" "$time" "$tz" "$at")
  PARITY_NAME="$name" PARITY_WORK="$WORK" PARITY_CHART="$chart_json" \
    PARITY_HARMONICS="$(printf '%s\n' "${MIDPOINT_HARMONICS[@]}" | paste -sd, - | sed 's/^/[/; s/$/]/')" \
    node --input-type=module -e "$TRIM" > "$WORK/parity-$name.json"
  cp "$WORK/parity-$name.json" "$OUT/parity-$name.json"
  echo "wrote test/fixtures/parity-$name.json"
  # The transit run comes after the parity trim, so the parity fixture's command list keeps the midpoint and harmonics runs only.
  if [ "$name" = "ny-1990" ]; then
    run_oracle "$name.transits.json" transits "${chart[@]}" "${PACK[@]}" --on "$TRANSIT_DATE" --on-time "$TRANSIT_TIME"
    PARITY_NAME="$name" PARITY_WORK="$WORK" PARITY_CHART="$chart_json" \
      node --input-type=module -e "$TRIM_TRANSITS" > "$WORK/parity-transits-$name.json"
    cp "$WORK/parity-transits-$name.json" "$OUT/parity-transits-$name.json"
    echo "wrote test/fixtures/parity-transits-$name.json"
  fi
done
